const PHASE4_UNLOCK_STORAGE_KEY = 'animal_budokai_phase4_unlocked_v1';

export function isPhase4Unlocked() {
  try {
    return window.localStorage.getItem(PHASE4_UNLOCK_STORAGE_KEY) === '1';
  } catch {
    return false;
  }
}

export function setPhase4Unlocked(unlocked = true) {
  try {
    if (unlocked) {
      window.localStorage.setItem(PHASE4_UNLOCK_STORAGE_KEY, '1');
    } else {
      window.localStorage.removeItem(PHASE4_UNLOCK_STORAGE_KEY);
    }
  } catch {
    // localStorage 無効環境時は安全に無視
  }
}

export function getPlayableCharacterOrder() {
  return isPhase4Unlocked() ? ALL_CHARACTER_ORDER : CHARACTER_ORDER;
}

